CODE_RX = re.compile(r'(?<![A-Za-z0-9])([A-Za-z]{2,6})[- ]?(\d{2,6})([A-Za-z]?)(?![A-Za-z0-9])')
CODE_SKIP = {'Q10', 'PS90', 'CA65', 'PE60'}


def code_key(letters, digits, tail=''):
    return f'{letters}{digits}{tail}'.upper()


def main():
    p = os.path.join(ROOT, 'data', 'official', 'I-0040.csv.gz')
    individual = []
    if os.path.exists(p):
        a = pd.read_csv(p, dtype=str).dropna(subset=['APLC_RAWMTRL_NM', 'FNCLTY_CN'])
        for _, r in a.iterrows():
            codes = sorted({code_key(*m.groups()) for m in CODE_RX.finditer(r['APLC_RAWMTRL_NM'])} - CODE_SKIP)
            if not codes:
                continue
            fn = [x.strip(' .') for x in re.split(r'[\n\r]+|(?<=있음)\s*[,·]\s*', r['FNCLTY_CN']) if x.strip(' .')]
            individual.append({'codes': codes, 'name': r['APLC_RAWMTRL_NM'].strip(), 'functions': fn,
                               'recog_no': r.get('HF_FNCLTY_MTRAL_RCOGN_NO', '')})
    data = {'note': '고시형: I0030 단일원료 제품의 기능성 문구를 정리(건강기능식품공전과 대조 필요). '
                    '개별인정형: I-0040 원료명의 원료 코드로 연결. 건강기능식품 원료로서의 인정 기능성이며 제품마다 신고 내용은 다를 수 있음.',
            'goshi': [{'name': n, 'pattern': pat, 'functions': fn, 'single_products': c} for n, pat, fn, c in GOSHI],
            'individual': individual}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(data, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'고시형 {len(GOSHI)}종, 개별인정형(코드 있음) {len(individual)}건 → {OUT}')


if __name__ == '__main__':
    main()
