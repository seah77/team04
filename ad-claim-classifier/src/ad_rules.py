def _has_any(t, words):
    return [w for w in words if w in t]


def rule_tags(text):
    """문장 하나 → [(태그, 근거 단어)]"""
    t = str(text)
    tags = []
    dis = _has_any(t, DISEASE)
    if dis:
        act = _has_any(t, DISEASE_ACT)
        tags.append(('질병 예방·치료 표현' if act else '질병명 포함', ', '.join(dis[:3] + act[:2])))
    drug = _has_any(t, DRUG_WORDS)
    for m in DRUG_SUFFIX.finditer(t):
        s = t[max(0, m.start() - 6):m.end()]
        word = re.findall(r'[가-힣]+\s?약$', s)
        if word and not any(word[0].replace(' ', '').endswith(n) for n in DRUG_NOT):
            drug.append(word[0])
    for rx in (DRUG_CLASS, DRUG_LIKE):
        m = rx.search(t)
        if m and not m.group(0).endswith('보조제'):
            drug.append(m.group(0))
    if DRUG_REPLACE.search(t):
        drug.append('의약품 대체 표현')
    if drug:
        tags.append(('의약품 연상 표현', ', '.join(dict.fromkeys(drug))))
    herb = _has_any(t, HERBAL)
