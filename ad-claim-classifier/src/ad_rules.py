def rule_vector(text):
    t = str(text)
    tags = {k for k, _ in rule_tags(t)}
    return [
        '질병명 포함' in tags or '질병 예방·치료 표현' in tags,
        '질병 예방·치료 표현' in tags,
        '의약품 연상 표현' in tags,
        '한약 처방명' in tags,
        '체험기·후기 표현' in tags,
        '인증·보증 표방' in tags,
        '"건강기능식품" 문구' in tags,
        '원료 효능 설명' in tags,
        bool(re.search(r'도움을?\s*줄\s*수\s*있', t)),
        bool(_has_any(t, EFFECT)),
        bool(re.search(r'\d', t)),
    ]


class RuleFeatures(BaseEstimator, TransformerMixin):
    """규칙 결과를 0/1 특징으로 만들어 TF-IDF 옆에 붙임 (pipeline에서 사용)"""
    def __init__(self, weight=1.0):
        self.weight = weight

    def fit(self, X, y=None):
        return self

    def transform(self, X):
        M = np.array([rule_vector(x) for x in X], dtype=float) * self.weight
        return sparse.csr_matrix(M)
