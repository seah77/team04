def targets(text):
    """문장이 말하는 기능 대상어 목록 (예: '간&장 더블케어' → ['간', '장'])"""
    t = str(text); found = []
    for w in sorted(TARGET_WORDS, key=len, reverse=True):
        i = t.find(w)
        if i >= 0 and not any(i >= a and i < b for a, b, _ in found):
            found.append((i, i + len(w), TARGET_ALIAS.get(w, w)))
    for m in _SINGLE_RX.finditer(t):
        if not any(m.start() >= a and m.start() < b for a, b, _ in found):
            found.append((m.start(), m.end(), TARGET_ALIAS.get(m.group(1), m.group(1))))
    out = []
    for _, _, w in sorted(found):
        if w not in out:
            out.append(w)
    return out


