def load_ingredients(i0040_path):
    """I-0040.csv.gz 의 원료명을 원료 사전에 추가 (괄호·영문 제거, 2~10자)"""
    import pandas as pd
    try:
        d = pd.read_csv(i0040_path, usecols=['APLC_RAWMTRL_NM'], dtype=str).dropna()
    except Exception:
        return 0
    add = set()
    for t in d['APLC_RAWMTRL_NM']:
        t = re.sub(r'\(.*?\)|\[.*?\]', '', t)
        for part in re.split(r'[,/·]| 및 ', t):
            for _ in range(2):
                part = re.sub(r'\s*(추출물|추출분말|분말|복합물|혼합물|등)\s*$', '', part.strip()).strip()
            if 2 <= len(part) <= 10 and re.search('[가-힣]', part):
                add.add(part)
    before = len(INGREDIENT)
    INGREDIENT.extend(sorted(add - set(INGREDIENT)))
    return len(INGREDIENT) - before


