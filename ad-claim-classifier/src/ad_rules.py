# ---------------------------------------------------------------- 문장 분리
_SPLIT = re.compile(r'(?<=[.!?。])\s+|[\n\r|/]+|\s{3,}|(?=#)|[•●▶▷■□◆◇※✔✓☆]+')


def split_sentences(text, min_len=2, max_len=80):
    """OCR 전체 글 → 문장 목록 (해시태그는 하나씩, 너무 긴 줄은 쉼표에서 자름)"""
    out = []
    for s in _SPLIT.split(str(text)):
        s = re.sub(r'\s+', ' ', s or '').strip(' -~·,.')
        if not s:
            continue
        parts = [s] if len(s) <= max_len else re.split(r'(?<=[,，])\s*', s)
        for p in parts:
            p = p.strip(' ,')
            if len(re.sub(r'[^가-힣A-Za-z0-9]', '', p)) >= min_len:
                out.append(p)
    return out


